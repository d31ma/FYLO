import { SiteArtifacts } from './site-artifacts.mjs'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { readFile, realpath, stat, writeFile } from 'node:fs/promises'
import {
    brotliCompressSync,
    brotliDecompressSync,
    constants,
    gunzipSync,
    gzipSync
} from 'node:zlib'

const project = process.argv[2] ? path.resolve(process.argv[2]) : process.cwd()
const web = SiteArtifacts.web(project)
const clientRuntime = path.join(web, '.tachyon', 'tac-client.js')

if (!(await Bun.file(clientRuntime).exists())) {
    throw new Error('Tachyon runtime is missing from the generated website')
}
if ((await Bun.file(clientRuntime).text()).includes('tachyon-expr[data-tachyon-expression]')) {
    throw new Error('Tachyon client runtime unexpectedly contains legacy expression markers')
}

const serviceWorkerFile = path.join(web, 'tachyon-sw.js')
const serviceWorker = await Bun.file(serviceWorkerFile).text()
const networkFirstRules = 'const RULES = ([{"pattern":"^/[^?]*$","policy":"network-first"}])'
const verifiedDispatch = `  const cacheFirst = !revalidate && (rule ? rule.policy === 'cache-first' : request.mode !== 'navigate')
  event.respondWith(cacheFirst ? fromCache(request, asset) : fromNetwork(request, asset))
`
const verifiedWorkerGuards = [
    'const ASSETS = {',
    'if (url.origin !== self.location.origin) return',
    "if (url.pathname.startsWith('/.tachyon/live-reload') || url.pathname === '/.tachyon/hot') return",
    "if (request.method !== 'GET' && request.method !== 'HEAD')",
    'event.respondWith(writeThrough(request, url))',
    "if (request.method === 'HEAD') return",
    'const asset = !url.search && Object.hasOwn(ASSETS, url.pathname) ? ASSETS[url.pathname] : null',
    "if (request.cache === 'no-store' || request.headers.has('authorization')",
    "|| request.headers.has('range') || rule?.policy === 'no-store'",
    "|| (!asset && (!rule || request.credentials !== 'omit')))",
    'const publicResponse = (response) => response && response.ok && !response.redirected',
    "&& response.type !== 'opaque' && response.type !== 'opaqueredirect'",
    "const variesOnlyByEncoding = (response) => (response.headers.get('vary') || '').split(',')",
    'if (asset && !await matchesAsset(await bodyBytes(response.clone(), asset.bodyLimit ?? 4 * 1024 * 1024), asset))',
    'if (asset && !await matchesAsset(bytes, asset)) { await evict(request); return }',
    'if (request.signal.aborted) throw error',
    'const cached = await cacheRead(request, asset)',
    "...(asset ? { credentials: 'omit' } : {})",
    'await bounded(cacheWrite(request, response, asset)).catch(() => {})',
    'if (name.startsWith(PREFIX) && name !== CACHE) await caches.delete(name)'
]

async function refreshAssetManifest(source) {
    const declaration = source.match(/^const ASSETS = (\{.*\})$/m)
    if (!declaration || !/^const VERSION = '[^']+'$/m.test(source)) {
        throw new Error('Tachyon verified asset manifest changed; refusing to rewrite it')
    }
    const assets = JSON.parse(declaration[1])
    const root = await realpath(web)
    const refreshed = Object.create(null)
    for (const url of Object.keys(assets)) {
        const pathname = decodeURIComponent(url)
        if (
            !pathname.startsWith('/') ||
            /[\\?#\0]/.test(pathname) ||
            pathname.split('/').some((part) => part === '.' || part === '..')
        ) {
            throw new Error('Tachyon verified asset manifest contains an unsafe path')
        }
        let file = path.join(root, pathname)
        if ((await stat(file)).isDirectory()) file = path.join(file, 'index.html')
        const resolved = await realpath(file)
        if (!resolved.startsWith(root + path.sep)) {
            throw new Error('Tachyon verified asset resolves outside the generated website')
        }
        const bytes = await readFile(resolved)
        refreshed[url] = {
            ...assets[url],
            bytes: bytes.byteLength,
            sha256: createHash('sha256').update(bytes).digest('hex')
        }
    }
    const manifest = JSON.stringify(refreshed)
    const version = createHash('sha256').update(manifest).digest('hex').slice(0, 16)
    return source
        .replace(declaration[0], `const ASSETS = ${manifest}`)
        .replace(/^const VERSION = '[^']+'$/m, `const VERSION = '${version}'`)
}

if (
    !verifiedWorkerGuards.every((guard) => serviceWorker.includes(guard)) ||
    !serviceWorker.includes(verifiedDispatch) ||
    !serviceWorker.includes(networkFirstRules)
) {
    throw new Error(
        'Tachyon service worker changed or is not network-first; refusing to refresh its asset manifest'
    )
}
// Hash the final generated bytes after fingerprinting; otherwise the upstream
// digest checks correctly refuse our modified HTML.
await Bun.write(serviceWorkerFile, await refreshAssetManifest(serviceWorker))
console.log('Refreshed the network-first Tachyon service worker hashes for the final bytes')

// Tachyon writes .br and .gz copies before FYLO fingerprints and patches the
// files. Rewrite every copy whose source bytes changed, so a server that sends
// a precompressed file sends the same bytes the worker verified.
const codecs = {
    br: {
        decode: brotliDecompressSync,
        encode: (bytes) =>
            brotliCompressSync(bytes, { params: { [constants.BROTLI_PARAM_QUALITY]: 11 } })
    },
    gz: { decode: gunzipSync, encode: (bytes) => gzipSync(bytes, { level: 9 }) }
}
let recompressed = 0
for await (const relative of new Bun.Glob('**/*.{br,gz}').scan({ cwd: web, dot: true })) {
    const copy = path.join(web, relative)
    const extension = relative.slice(relative.lastIndexOf('.') + 1)
    const source = copy.slice(0, -extension.length - 1)
    if (!(await Bun.file(source).exists())) continue
    const bytes = await readFile(source)
    if (codecs[extension].decode(await readFile(copy)).equals(bytes)) continue
    await writeFile(copy, codecs[extension].encode(bytes))
    recompressed++
}
console.log(`Rewrote ${recompressed} precompressed copies of changed files`)
